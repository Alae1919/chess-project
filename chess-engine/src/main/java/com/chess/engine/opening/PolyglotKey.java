    // Piece-index mapping (Polyglot order: black pieces first)
    // bP=0, bN=1, bB=2, bR=3, bQ=4, bK=5, wP=6, wN=7, wB=8, wR=9, wQ=10, wK=11
    private static final int IDX_CASTLING   = 768;
    private static final int IDX_EP         = 772;
    private static final int IDX_SIDE       = 780;

    private PolyglotKey() {}

    /**
     * Computes the Polyglot hash for the given board.
     * This hash matches the keys stored in standard Polyglot .bin book files.
     */
    public static long compute(Board board) {
        long key = 0L;

        // Pieces
        for (int f = 0; f < Board.SIZE; f++) {
            for (int r = 0; r < Board.SIZE; r++) {
                var opt = board.pieceAt(new Square(f, r));
                if (opt.isPresent()) {
                    int pieceIdx = polyglotPieceIndex(opt.get());
                    int sq = f + r * 8;  // a1=0, b1=1, …, h8=63
                    key ^= RANDOM_64[pieceIdx * 64 + sq];
                }
            }
        }

        // Castling rights (Polyglot order: wK=0, wQ=1, bK=2, bQ=3)
        CastlingRights cr = board.castlingRights();
        if (cr.whiteKingSide())  key ^= RANDOM_64[IDX_CASTLING];
        if (cr.whiteQueenSide()) key ^= RANDOM_64[IDX_CASTLING + 1];
        if (cr.blackKingSide())  key ^= RANDOM_64[IDX_CASTLING + 2];
        if (cr.blackQueenSide()) key ^= RANDOM_64[IDX_CASTLING + 3];

        // En passant (only if there is a pawn that can actually capture)
        var ep = board.enPassantTarget();
        if (ep.isPresent()) key ^= RANDOM_64[IDX_EP + ep.get().file()];

        // Side to move: Polyglot XORs in the constant when WHITE is to move
        // (inverse of most engines which XOR for black)
        if (board.activeColor() == Color.WHITE) key ^= RANDOM_64[IDX_SIDE];

        return key;
    }

    /**
     * Polyglot piece index: black pieces first (0=bP…5=bK), then white (6=wP…11=wK).
     */
    private static int polyglotPieceIndex(Piece p) {
        int typeIdx = switch (p.type()) {
            case PAWN   -> 0;
            case KNIGHT -> 1;
            case BISHOP -> 2;
            case ROOK   -> 3;
            case QUEEN  -> 4;
            case KING   -> 5;
        };
        // White pieces are offset by 6
        return p.color() == Color.BLACK ? typeIdx : typeIdx + 6;
    }

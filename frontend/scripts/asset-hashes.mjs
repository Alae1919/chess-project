#!/usr/bin/env node
// Writes src/app/core/assets/asset-hashes.generated.ts: a short content hash for every file under
// src/assets. assetUrl() (asset-url.ts) adds it to the file's URL as ?v=<hash>, so a URL names one
// exact version of a file and nginx can let browsers keep it for a year (see nginx.conf): a changed
// file gets a new URL, an unchanged one keeps its URL, and stays cached, across deploys.
//
// Run by npm before build, start and test (the pre* scripts in package.json); the output is not
// committed, so it can never fall behind the files.

import { createHash } from 'node:crypto';
import { readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import { join, relative, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('..', import.meta.url));
const src = join(root, 'src');
const out = join(src, 'app/core/assets/asset-hashes.generated.ts');

function* files(dir) {
  for (const name of readdirSync(dir).sort()) {
    const path = join(dir, name);
    if (statSync(path).isDirectory()) yield* files(path);
    else if (!name.startsWith('.') && !name.endsWith('.md')) yield path;
  }
}

const hashes = {};
for (const path of files(join(src, 'assets'))) {
  const key = relative(src, path).split(sep).join('/');
  hashes[key] = createHash('sha256').update(readFileSync(path)).digest('hex').slice(0, 10);
}

const body = Object.entries(hashes).map(([k, v]) => `  '${k}': '${v}',`).join('\n');
const text = `// Generated by scripts/asset-hashes.mjs before every build: do not edit, and do not commit.
/** A content hash of each file under src/assets, by its path from src/ */
export const ASSET_HASHES: Readonly<Record<string, string>> = {
${body}
};
`;

let previous = '';
try { previous = readFileSync(out, 'utf8'); } catch { /* first run */ }
// unchanged: leave the file alone, so a running dev server does not rebuild for nothing
if (previous !== text) writeFileSync(out, text);
console.log(`asset-hashes: ${Object.keys(hashes).length} files`);
